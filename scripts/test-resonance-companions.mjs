import assert from "node:assert/strict";
import { completeWish, dateKey, milestoneOccurrence, readStore, storageKey, validDate } from "../app/resonance/store.ts";

const values = new Map();
globalThis.localStorage = { getItem: (key) => values.get(key) ?? null };
const relationship = { id: "test", kind: "partner", createdAt: new Date().toISOString(), posts: [] };
const save = () => values.set(storageKey, JSON.stringify({ version: 1, relationships: [relationship], invites: {} }));
save();
assert.deepEqual(readStore().relationships[0].posts, []);
assert.equal(validDate("2026-02-30"), false);
assert.equal(validDate("2028-02-29"), true);
const anniversary = { id: "leap", title: "纪念日", date: "2024-02-29", time: "09:30", yearly: true };
assert.equal(dateKey(milestoneOccurrence(anniversary, new Date(2026, 1, 1))), "2026-02-28");
assert.equal(dateKey(milestoneOccurrence(anniversary, new Date(2028, 1, 1))), "2028-02-29");
assert.equal(dateKey(milestoneOccurrence({ ...anniversary, date: "2028-02-29" }, new Date(2026, 1, 1))), "2028-02-29");
relationship.wishes = [{ id: "sea", title: "一起看海", createdAt: new Date().toISOString() }, { id: "cook", title: "做晚餐", createdAt: new Date().toISOString() }];
assert.throws(() => completeWish(relationship, "sea", "2026-02-30", "self", true, ""));
completeWish(relationship, "sea", "2026-11-22", "other", true, " 看到了日落 ");
assert.equal(relationship.posts.length, 1);
assert.equal(relationship.posts[0].date, "2026-11-22");
assert.equal(relationship.posts[0].author, "other");
assert.match(relationship.posts[0].text, /看到了日落/);
assert.equal(relationship.wishes[0].postId, relationship.posts[0].id);
completeWish(relationship, "sea", "2026-11-22", "self", true, "重复提交");
assert.equal(relationship.posts.length, 1);
completeWish(relationship, "cook", "2026-11-22", "self", false, "");
assert.equal(relationship.posts.length, 1);
assert.equal(relationship.wishes[1].diaryDate, undefined);
relationship.milestones = [anniversary];
relationship.pet = { name: "小琴", feeds: 1, fedOn: "2026-11-22" };
save();
assert.equal(readStore().relationships[0].wishes[0].diaryDate, "2026-11-22");
relationship.pet.feeds = -1;
save();
assert.throws(() => readStore());
console.log("PASS: old data, dates, leap anniversaries, future dates, diary links, duplicate completion, optional diary, persistence and invalid data.");
